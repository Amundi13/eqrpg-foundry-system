import assert from "node:assert/strict";
import {planPackUpgrade,applyPackUpgrade,sourceIdFor,resolvePackConflict} from "../module/packs/pack-upgrades.mjs";
import * as sample from "../module/packs/sample-data.mjs";
import {PHB_JOURNALS} from "../module/packs/phb-data.mjs";
const packId="eqrpg.test";
const source={name:"Shield",type:"armor",system:{acBonus:2,description:"Original"}};
const first=planPackUpgrade(packId,[source],[]);
assert.equal(first.creates.length,1);
assert.match(first.creates[0]._id,/^[a-f0-9]{16}$/);
const imported=structuredClone(first.creates[0]);imported._id="existingActorRef1";
assert.equal(planPackUpgrade(packId,[source],[imported]).unchanged,1);
const next=structuredClone(source);next.system.acBonus=3;
const edited=structuredClone(imported);edited.system.description="GM notes";edited.flags.anotherModule={enabled:true};
const upgrade=planPackUpgrade(packId,[next],[edited]);
assert.equal(upgrade.updates[0].patch._id,edited._id);
assert.equal(upgrade.updates[0].patch["system.acBonus"],3);
assert.ok(!("system.description" in upgrade.updates[0].patch));
assert.ok(!("flags.anotherModule" in upgrade.updates[0].patch));
const conflict=structuredClone(edited);conflict.system.acBonus=4;
assert.equal(planPackUpgrade(packId,[next],[conflict]).conflicts[0].reason,"local-edits-or-embedded-content");
assert.equal(planPackUpgrade(packId,[next],[conflict]).updates.length,0);
const legacy={_id:"legacyReference1",...structuredClone(source)};
assert.equal(planPackUpgrade(packId,[source],[legacy]).updates[0].adoption,true);
assert.equal(planPackUpgrade(packId,[next],[legacy]).conflicts[0].reason,"legacy-needs-review");
assert.equal(planPackUpgrade(packId,[source],[legacy,{...legacy,_id:"legacyReference2"}]).conflicts[0].reason,"ambiguous-match");
assert.equal(planPackUpgrade(packId,[],[imported]).retained.length,1);
assert.throws(()=>planPackUpgrade(packId,[source,source],[]),/Duplicate source/);
const renamed=structuredClone(next);renamed.name="Renamed Shield";renamed.flags={eqrpg:{sourceId:sourceIdFor(packId,source)}};
assert.equal(planPackUpgrade(packId,[renamed],[imported]).updates[0].patch.name,"Renamed Shield");
const removed=structuredClone(source);delete removed.system.acBonus;
assert.equal(planPackUpgrade(packId,[removed],[imported]).updates[0].patch["system.-=acBonus"],null);

let documents=[structuredClone(edited)], writes=0;const lockChanges=[];
function applyFlat(target,patch){for(const [path,value] of Object.entries(patch)){if(path==="_id")continue;const parts=path.split(".");let node=target;for(const key of parts.slice(0,-1))node=node[key]??={};const key=parts.at(-1);if(key.startsWith("-="))delete node[key.slice(2)];else node[key]=structuredClone(value);}}
const pack={collection:packId,locked:true,async getDocuments(){return structuredClone(documents);},async configure({locked}){this.locked=locked;lockChanges.push(locked);},documentClass:{async updateDocuments(updates){writes++;for(const patch of updates)applyFlat(documents.find(doc=>doc._id===patch._id),patch);return updates.map(patch=>documents.find(doc=>doc._id===patch._id));},async createDocuments(data){writes++;documents.push(...structuredClone(data));return data;},async deleteDocuments(){assert.fail("Upgrades must never delete entries");}}};
const result=await applyPackUpgrade(pack,upgrade);
assert.equal(result.updated,1);assert.equal(documents[0].system.description,"GM notes");assert.deepEqual(lockChanges,[false,true]);
const repeat=planPackUpgrade(packId,[next],documents);assert.equal(repeat.updates.length,0);assert.equal(repeat.unchanged,1);
await applyPackUpgrade(pack,repeat);assert.equal(writes,1);
const stale=planPackUpgrade(packId,[source],documents);documents[0].system.description="Edited after preview";
await assert.rejects(applyPackUpgrade(pack,stale),/changed after preview/);assert.equal(writes,1);
const failure=planPackUpgrade(packId,[source],documents);
pack.documentClass.updateDocuments=async()=>{throw new Error("Simulated write failure");};
await assert.rejects(applyPackUpgrade(pack,failure),error=>error.message==="Simulated write failure"&&error.upgradeProgress.updated===0);
assert.equal(pack.locked,true);
pack.documentClass.updateDocuments=async()=>[];
await assert.rejects(applyPackUpgrade(pack,failure),/not confirmed/);
assert.equal(pack.locked,true);
for(const [name,data] of Object.entries(sample)) if(Array.isArray(data)) assert.equal(planPackUpgrade(`eqrpg.${name}`,data,[]).creates.length,data.length);
assert.equal(planPackUpgrade("eqrpg.eqrpg-phb",PHB_JOURNALS,[]).creates.length,PHB_JOURNALS.length);
const pinned=structuredClone(source);pinned.flags={eqrpg:{sourceId:sourceIdFor(packId,source)}};
const corrected=structuredClone(pinned);corrected.name="New name";corrected.system.classLevels=["wizard:2"];
assert.equal(sourceIdFor(packId,corrected),sourceIdFor(packId,pinned),"pinned IDs survive source corrections");
assert.equal(planPackUpgrade(packId,[pinned],[legacy]).updates[0].adoption,true,"matching legacy data can adopt a pinned identity without rewriting content");
const shapeChange=structuredClone(source);shapeChange.system.acBonus={value:2};
assert.equal(planPackUpgrade(packId,[shapeChange],[imported]).conflicts.length,1);
const legacyPlan=planPackUpgrade(packId,[next],[legacy]);
const approved=resolvePackConflict(legacyPlan,legacy._id,{"system.acBonus":"source"});
assert.equal(approved.updates[0].patch["system.acBonus"],3);assert.equal(approved.updates[0].patch._id,legacy._id);assert.equal(approved.conflicts.length,0);assert.equal(legacyPlan.conflicts.length,1);
const kept=resolvePackConflict(legacyPlan,legacy._id,{"system.acBonus":"local"});assert.ok(!("system.acBonus" in kept.updates[0].patch));
assert.throws(()=>resolvePackConflict(legacyPlan,legacy._id,{}),/Choose source or local/);
assert.throws(()=>resolvePackConflict(legacyPlan,legacy._id,{"system.acBonus":"source","system.extra":"source"}),/outside/);
documents=[];
const createdResult=await applyPackUpgrade(pack,first);
assert.equal(createdResult.created,1);assert.equal(documents[0]._id,first.creates[0]._id);
const initialized=planPackUpgrade(packId,[source],documents);assert.equal(initialized.unchanged,1);assert.equal(initialized.creates.length,0);
console.log("Pack upgrade checks passed (preserved IDs/local edits, conflicts, retries, stale plans, failures, deterministic identities).");
