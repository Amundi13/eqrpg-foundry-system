import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
const root=fileURLToPath(new URL('../',import.meta.url));
const original=path.resolve(process.argv[2]??'');
const scratch=fs.mkdtempSync(path.join(root,'dist','pack-verification-'));
fs.cpSync(original,path.join(scratch,'packs'),{recursive:true});
const reportPath=path.join(scratch,'build-report.json');
const report=JSON.parse(fs.readFileSync(path.join(original,'..','build-report.json'),'utf8'));
fs.writeFileSync(reportPath,JSON.stringify(report));
const verify=()=>spawnSync(process.execPath,[path.join(root,'scripts/verify-pack-build.mjs'),path.join(scratch,'packs')],{encoding:'utf8'});
assert.equal(verify().status,0,'unchanged copy must verify');
fs.writeFileSync(reportPath,JSON.stringify({...report,inputDigest:'stale'}));
let failure=verify();assert.notEqual(failure.status,0);assert.match(failure.stderr,/no longer match current source inputs/);
fs.writeFileSync(reportPath,JSON.stringify(report));
const target=path.join(scratch,'packs',Object.keys(report.hashes)[0]);
fs.appendFileSync(target,'changed');
failure=verify();assert.notEqual(failure.status,0);assert.match(failure.stderr,/database bytes changed/);
console.log('Pack verification rejects stale input reports and modified database files; only disposable copies were changed.');
